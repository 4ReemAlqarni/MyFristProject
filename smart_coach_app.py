import streamlit as st

# واجهة العنوان
st.set_page_config(page_title="مساعد المدرب الذكي - تجربة المدرب الواقعي", layout="centered")
st.title("مساعد المدرب الذكي - تجربة المدرب الواقعي")
st.markdown("### بيانات تفاعلية تساعدك تتخذ القرار الصح في الوقت الصح.")

# تبويبات العرض
tab1, tab2, tab3 = st.tabs(["تحليل الفيديو", "تحليل الإرهاق البدني", "التوصيات التكتيكية"])

# --- تبويب 1: تتبع وتحليل الأداء ---
with tab1:
    st.subheader("تحليل الأداء من الفيديو")
    st.markdown("نعتمد على كاميرات الملاعب مع خوارزميات الذكاء الاصطناعي لتحديد موقع اللاعبين وتتبع تحركاتهم.")
    st.video("match_sample.mp4")
    st.caption("تموضع وتتبع اللاعبين في الوقت الفعلي")

# --- تبويب 2: تحليل الإرهاق البدني ---
with tab2:
    st.subheader("تحليل الإرهاق البدني")
    st.markdown("نحسب مستوى الإرهاق وفقًا لمعدل نبضات القلب، والسرعة، والمسافة المقطوعة.")

    hr = st.slider("نبضات القلب (bpm)", 60, 200, 120)
    speed = st.slider("السرعة (كم/ساعة)", 0, 40, 20)
    distance = st.slider("المسافة المقطوعة (كم)", 0, 15, 7)

    fatigue_score = (hr / 200) * 0.4 + (speed / 40) * 0.3 + (distance / 15) * 0.3

    if fatigue_score > 0.75:
        status = "مرهق جدًا - يُفضل الاستبدال"
        st.error(status)
    elif fatigue_score > 0.5:
        status = "متوسط الإرهاق - راقبه باستمرار"
        st.warning(status)
    else:
        status = "منخفض الإرهاق - جاهز للاستمرار"
        st.success(status)

# --- تبويب 3: التوصيات التكتيكية ---
with tab3:
    st.subheader("التوصيات التكتيكية حسب تمركز اللاعبين")
    st.markdown("أدخل تمركز اللاعبين لتصلك توصية فورية:")

    left_wing = st.slider("التمركز في الجناح الأيسر", 0, 100, 75)
    center_defense = st.slider("التمركز في الدفاع الأوسط", 0, 100, 25)

    if left_wing > 70:
        st.info("التوصية: اضغط من الجهة اليمنى")
    elif center_defense < 30:
        st.info("التوصية: اخترق من المنتصف")
    else:
        st.info("التوصية: حافظ على التوزيع الحالي")